    private void iniciarSesion() {
        String usuario = jtextFieldUser.getText();
        String clave = new String(jpasswordField.getPassword());

        try {
            Administrador administrador = administradorServicio.iniciarSesion(usuario, clave);
            if (administrador == null) {
                JOptionPane.showMessageDialog(this, "Usuario o clave incorrectos.");
                jpasswordField.setText("");
                jpasswordField.requestFocusInWindow();
                return;
            }

            VistaAdmin admin = new VistaAdmin();
            admin.setLocationRelativeTo(this);
            admin.setVisible(true);
            dispose();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this,
                    "No se pudo iniciar sesión: " + ex.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void volverALectura() {
        VistaAcceso acceso = new VistaAcceso();
        acceso.setVisible(true);
        dispose();
    }

