    private void configurarFocoDeLectura() {
        addWindowListener(new WindowAdapter() {
            @Override
            public void windowOpened(WindowEvent evento) {
                jtxtRFIDTextWaiting.requestFocusInWindow();
            }

            @Override
            public void windowActivated(WindowEvent evento) {
                jtxtRFIDTextWaiting.requestFocusInWindow();
            }
        });
    }

    private void procesarLectura() {
        String codigo = jtxtRFIDTextWaiting.getText().trim();
        if (codigo.isEmpty()) {
            jtxtRFIDTextWaiting.requestFocusInWindow();
            return;
        }

        try {
            Estudiante estudiante = accesoServicio.procesarCodigo(codigo);
            if (estudiante == null) {
                mostrarAccesoDenegado();
            } else {
                mostrarAutenticado(estudiante);
            }
        } catch (SQLException | IllegalArgumentException ex) {
            estadoLabel.setText("Error al registrar la lectura");
            estadoLabel.setForeground(Color.RED);
            NombreLabel.setText("Nombre:");
            CarreraLabel.setText("Carrera:");
            JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        } finally {
            jtxtRFIDTextWaiting.setText("");
            jtxtRFIDTextWaiting.requestFocusInWindow();
        }
    }

    private void mostrarAutenticado(Estudiante estudiante) {
        estadoLabel.setText("Autenticado");
        estadoLabel.setForeground(new Color(0, 128, 0));
        NombreLabel.setText("Nombre: " + estudiante.getNombres());
        CarreraLabel.setText("Carrera: " + estudiante.getCarrera());
    }

    private void mostrarAccesoDenegado() {
        estadoLabel.setText("Acceso denegado");
        estadoLabel.setForeground(Color.RED);
        NombreLabel.setText("Nombre:");
        CarreraLabel.setText("Carrera:");
    }

    private void abrirLogin() {
        VistaLogin login = new VistaLogin();
        login.setLocationRelativeTo(this);
        login.setVisible(true);
        this.setVisible(false);
    }

